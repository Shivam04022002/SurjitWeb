const analyticsService = require('../services/analytics.service');
const { sendSuccess } = require('../utils/response');
const HTTP_STATUS = require('../constants/httpStatus');
const asyncHandler = require('../utils/asyncHandler');

// Derives a coarse device bucket from the user-agent and then discards it —
// the raw string is never stored.
const deviceTypeFrom = (userAgent = '') => {
    const ua = String(userAgent).toLowerCase();
    if (!ua) return 'unknown';
    if (/ipad|tablet|playbook|silk/.test(ua)) return 'tablet';
    if (/mobi|android|iphone|ipod|windows phone/.test(ua)) return 'mobile';
    return 'desktop';
};

// Referring host only. A full referrer URL can carry paths and query strings
// from other sites, which is more than this needs.
const referrerHost = (referrer) => {
    if (!referrer) return '';
    try {
        return new URL(referrer).hostname.slice(0, 200);
    } catch {
        return '';
    }
};

// ── Public ─────────────────────────────────────────────────────────────────────

// Anonymous page-view beacon from the public website. Nothing here identifies a
// person: the session id is generated by the browser for itself, and no IP or
// user-agent string is persisted.
const trackPageView = asyncHandler(async (req, res) => {
    await analyticsService.recordPageView({
        sessionId: req.body.sessionId,
        path: req.body.path,
        referrer: referrerHost(req.body.referrer),
        deviceType: deviceTypeFrom(req.headers['user-agent']),
        sessionStartedAt: req.body.sessionStartedAt ? new Date(req.body.sessionStartedAt) : new Date()
    });

    // Nothing useful to hand back to a tracking beacon.
    return sendSuccess(res, 'Recorded', {}, HTTP_STATUS.CREATED);
});

// ── Admin ──────────────────────────────────────────────────────────────────────

const getOverview = asyncHandler(async (req, res) => {
    // `range` is validated against an allowlist before reaching here.
    const overview = await analyticsService.getOverview(req.query.range);
    return sendSuccess(res, 'Analytics fetched successfully', overview, HTTP_STATUS.OK);
});

module.exports = { trackPageView, getOverview };
